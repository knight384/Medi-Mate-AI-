"""
MediMate AI — Internal Service Assertion Validator & Trust Boundary
Verifies cryptographic HMAC-SHA256 assertions generated by the Next.js backend.
Strictly prohibits reliance on untrusted client headers.
"""

import base64
import hashlib
import hmac
import json
import time
from typing import Any, Dict, Optional, Set
from pydantic import BaseModel, Field

from app.core.config import settings
from app.core.errors import AuthenticationError, ForbiddenOperationError
from app.core.logging import logger
from app.security.replay import get_replay_registry


class InternalServiceClaims(BaseModel):
    """Cryptographically validated claims issued by the internal backend."""

    sub: str = Field(description="Authenticated subject / user ID")
    tenantId: str = Field(description="Validated tenant identifier")
    op: str = Field(description="Authorized operation: INGEST | QUERY | DELETE")
    resourceId: Optional[str] = Field(default=None, description="Optional bound resource / document ID")
    purpose: str = Field(default="CLINICAL_RAG_RETRIEVAL", description="Declared processing purpose")
    iss: str = Field(default="medimate-web", description="Issuer (must be medimate-web)")
    aud: str = Field(default="medimate-rag", description="Audience (must be medimate-rag)")
    iat: int = Field(description="Issued at epoch timestamp")
    exp: int = Field(description="Expiration epoch timestamp")
    nonce: str = Field(description="Cryptographic nonce for replay protection")


class AssertionReplayCache:
    """Bounded in-memory cache to detect and reject replayed assertion nonces."""

    def __init__(self, max_entries: int = 10000):
        self._cache: Dict[str, float] = {}  # nonce -> expiry
        self._max_entries = max_entries

    def is_replayed(self, nonce: str, exp: float) -> bool:
        now = time.time()
        # Periodic cleanup of expired nonces
        if len(self._cache) > self._max_entries:
            self._cache = {n: e for n, e in self._cache.items() if e > now}

        if nonce in self._cache:
            return True

        self._cache[nonce] = exp
        return False


_replay_cache = AssertionReplayCache()


def _b64url_decode(input_str: str) -> bytes:
    """Decodes standard or URL-safe base64 string with padding compensation."""
    rem = len(input_str) % 4
    if rem > 0:
        input_str += "=" * (4 - rem)
    return base64.urlsafe_b64decode(input_str.encode("utf-8"))


def _b64url_encode(data: bytes) -> str:
    """Encodes bytes into URL-safe base64 string without trailing padding."""
    return base64.urlsafe_b64encode(data).decode("utf-8").rstrip("=")


def create_internal_assertion(
    sub: str,
    tenant_id: str,
    op: str,
    resource_id: Optional[str] = None,
    purpose: str = "CLINICAL_RAG_RETRIEVAL",
    secret: Optional[str] = None,
    expires_in_seconds: int = 60,
    nonce: Optional[str] = None,
) -> str:
    """
    Generates a cryptographically signed HMAC-SHA256 service assertion.
    Mirror utility used by internal backend and integration test harness.
    """
    sec = secret or settings.internal_service_secret
    now = int(time.time())
    import uuid

    claims = {
        "sub": sub,
        "tenantId": tenant_id,
        "op": op,
        "resourceId": resource_id,
        "purpose": purpose,
        "iss": "medimate-web",
        "aud": "medimate-rag",
        "iat": now,
        "exp": now + expires_in_seconds,
        "nonce": nonce or uuid.uuid4().hex,
    }

    header = {"alg": "HS256", "typ": "INTERNAL_ASSERTION"}
    header_b64 = _b64url_encode(json.dumps(header, separators=(",", ":")).encode("utf-8"))
    payload_b64 = _b64url_encode(json.dumps(claims, separators=(",", ":")).encode("utf-8"))
    signing_input = f"{header_b64}.{payload_b64}".encode("utf-8")

    sig = hmac.new(sec.encode("utf-8"), signing_input, hashlib.sha256).digest()
    sig_b64 = _b64url_encode(sig)

    return f"{header_b64}.{payload_b64}.{sig_b64}"


def verify_service_assertion(
    assertion_token: str,
    expected_op: Optional[str] = None,
    expected_resource_id: Optional[str] = None,
    secret: Optional[str] = None,
) -> InternalServiceClaims:
    """
    Verifies the internal service assertion token:
    1. Validates structure: header.payload.signature
    2. Validates HMAC-SHA256 signature using constant-time comparison
    3. Validates expiration and clock skew
    4. Validates issuer (medimate-web) and audience (medimate-rag)
    5. Validates operation and bound resourceId
    6. Verifies nonce freshness against replay attacks
    """
    if not assertion_token or not isinstance(assertion_token, str):
        raise AuthenticationError("Missing internal service assertion token")

    parts = assertion_token.strip().split(".")
    if len(parts) != 3:
        raise AuthenticationError("Malformed service assertion format")

    header_b64, payload_b64, signature_b64 = parts
    sec = secret or settings.internal_service_secret

    # Verify signature
    signing_input = f"{header_b64}.{payload_b64}".encode("utf-8")
    expected_sig = hmac.new(sec.encode("utf-8"), signing_input, hashlib.sha256).digest()
    expected_sig_b64 = _b64url_encode(expected_sig)

    if not hmac.compare_digest(signature_b64, expected_sig_b64):
        logger.warning(
            "Service assertion signature mismatch",
            extra={"structured_data": {"event": "AUTH_SIGNATURE_MISMATCH"}}
        )
        raise AuthenticationError("Invalid service assertion signature")

    # Decode and parse payload
    try:
        payload_bytes = _b64url_decode(payload_b64)
        payload_dict = json.loads(payload_bytes.decode("utf-8"))
        claims = InternalServiceClaims.model_validate(payload_dict)
    except Exception as e:
        logger.warning(f"Failed to parse assertion claims: {str(e)}")
        raise AuthenticationError("Corrupt assertion claims payload")

    now = time.time()
    # Check expiration with clock skew
    if now > claims.exp + settings.assertion_clock_skew_seconds:
        raise AuthenticationError("Service assertion has expired")

    if claims.iat > now + settings.assertion_clock_skew_seconds:
        raise AuthenticationError("Service assertion issued in the future")

    # Validate audience and issuer
    if claims.iss != "medimate-web":
        raise AuthenticationError(f"Untrusted assertion issuer: {claims.iss}")

    if claims.aud != "medimate-rag":
        raise AuthenticationError(f"Invalid assertion audience: {claims.aud}")

    # Validate operation scope
    if expected_op and claims.op != expected_op:
        raise ForbiddenOperationError(
            f"Assertion op '{claims.op}' does not permit expected operation '{expected_op}'"
        )

    # Validate resource scope if bound
    if claims.resourceId and expected_resource_id and claims.resourceId != expected_resource_id:
        raise ForbiddenOperationError(
            f"Assertion resourceId '{claims.resourceId}' does not match target '{expected_resource_id}'"
        )

    # Replay protection check
    registry = get_replay_registry()
    if not registry.register_nonce(claims.nonce, claims.exp):
        logger.warning(
            "Service assertion replay detected",
            extra={"structured_data": {"nonce": claims.nonce, "sub": claims.sub}}
        )
        raise AuthenticationError("Service assertion nonce has already been consumed (replay rejected)")

    return claims
